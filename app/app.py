def _default_project_id(requested_id=None):
    """
    Resolves which project id the dashboard/explorer should default to: the
    `?project=` query param if valid, otherwise the first project with at
    least one file, otherwise the first project, otherwise None (no projects
    at all yet).
    """
    Database.open_connexion()
    try:
        projects = Database.get_projects()
        if isinstance(projects, dict):
            projects = [projects]
        files = Database.get_files()
        if isinstance(files, dict):
            files = [files]
    finally:
        Database.close_connexion()

    if not projects:
        return None

    project_ids = {p["id_project"] for p in projects}
    if requested_id is not None and requested_id in project_ids:
        return requested_id

    projects_with_files = {f["id_project"] for f in files}
    for p in projects:
        if p["id_project"] in projects_with_files:
            return p["id_project"]

    return projects[0]["id_project"]



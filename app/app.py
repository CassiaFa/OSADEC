# Check if file have the good extension
def allowed_file(filename):
    return '.' in filename and \
           filename.rsplit('.', 1)[1].lower() in ALLOWED_EXTENSIONS

# `Database` (src/utils/db_tools.py) holds its MySQL connection/cursor as class
# attributes shared by the whole process rather than one per request/thread.
# That predates this redesign and is out of scope to fix here, but Phase 5
# introduces a genuinely concurrent writer (the background analysis task can
# still be running - and writing detections - while the main thread serves
# another request). This lock at least serializes the upload route's own two
# Database-using sections (file registration, then the background job's
# detection writes) against each other and against concurrent uploads, so two
# background jobs (or an upload and its own background job) can't interleave
# `execute()`/`fetchall()` calls on the single shared cursor. It does not
# protect the other routes (`/account`, `/file_info`, `/api/...`), which can
# still race a running background job - a full per-request-connection refactor
# of `Database` is a separate, larger piece of work.
_db_lock = threading.Lock()


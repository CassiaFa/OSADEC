@socketio.on('connect', namespace='/progress')
def handle_connect():
    # Flask-SocketIO automatically keeps every connected client in a private
    # room named after its own `request.sid` - `_emit_progress` below targets
    # that room instead of broadcasting to the whole `/progress` namespace.
    print(f'Client connected: {request.sid}')


def _emit_progress(sid, payload):
    """
    Emits a 'progress' event on the /progress namespace targeted at a single
    client (the one identified by `sid`, a Socket.IO connection id the client
    passes back to `POST /upload` - see static/js/dropzone.js). Replaces the
    historical `socketio.emit(..., namespace='/progress')` broadcast, which
    used to reach every connected client regardless of who triggered the
    upload.

    If `sid` is falsy (e.g. a non-browser caller that never passed one), the
    event is dropped rather than falling back to a broadcast: there is no
    single legitimate recipient to target anymore.
    """
    if not sid:
        return
    socketio.emit('progress', payload, namespace='/progress', room=sid)


def _run_analysis_job(job_id, sid, file_path, file_name, id_file, acquisition_date, duration, fs, species_map):
    """
    Background task (started from `handle_upload` via
    `socketio.start_background_task`): runs the detection pipeline and
    persists its results, reporting progress per analysis window to the single
    client identified by `sid`.

    Runs outside of any Flask request context (that's the point - it must not
    block the request that triggered it), so it must not touch
    `flask.request`/`flask.session`; everything it needs is passed in as
    plain arguments by `handle_upload`, including `species_map` (fetched once,
    synchronously, by `handle_upload` itself): this means `pipeline()` never
    needs its own database connection open during the (potentially long)
    inference loop, only `_db_lock`/`Database.open_connexion()` around the
    final detection writes below.
    """

    def progress(percent, message, status='loading'):
        _emit_progress(sid, {
            'job_id': job_id,
            'id_file': id_file,
            'percent': percent,
            'message': message,
            'status': status,
        })

    try:
        progress(10, 'Computing detection pipeline ...')

        def window_progress(index, total):
            # Map per-window progress onto the 10-85% band: the upload itself
            # (0-10%) already happened synchronously in handle_upload, and
            # writing detections to the database (85-100%) happens below.
            percent = 10 + int(75 * index / total) if total else 85
            progress(percent, f'Window {index}/{total}')

        print(f"[{job_id}] Pipeline started for {file_name}")
        result = pipeline(
            file_path, acquisition_date, duration, fs,
            progress_callback=window_progress, species_map=species_map,
        )

        progress(85, 'Pipeline finished, writing detections ...')

        with _db_lock:
            Database.open_connexion()
            try:
                for det in result:
                    Database.add_detection(
                        det["start"], det["end"], det["confidence"],
                        det["id_species"], id_file, det["fmin"], det["fmax"],
                    )
            finally:
                Database.close_connexion()

        if result:
            print(f"[{job_id}] {len(result)} detection(s) added to database")
        else:
            print(f"[{job_id}] No detections")

        progress(100, 'Analysis complete', status='complete')

    except Exception:
        print(f"[{job_id}] Analysis failed:")
        traceback.print_exc()
        progress(100, 'Analysis failed, see server logs.', status='error')


@app.route('/upload', methods=['POST'])
def handle_upload():

    # Step 1: Upload the file. Kept synchronous (fast, and the rest of this
    # handler needs the file on disk to read its duration/samplerate before it
    # can register it) - only the detection pipeline (step 3) and the
    # detection writes (step 4) move to a background task.

    uploaded = [f for key, f in request.files.items() if key.startswith('file')]
    if not uploaded or not uploaded[0].filename:
        return jsonify({'error': 'bad_request', 'message': 'No file provided.'}), 400

    f = uploaded[0]
    if not allowed_file(f.filename):
        return jsonify({'error': 'bad_request', 'message': 'Only .wav files are accepted.'}), 400

    # Socket.IO connection id of the client's own /progress namespace
    # connection (see static/js/dropzone.js / templates/account.html) - used
    # to target progress events at this client only.
    sid = request.values.get('sid')

    file_name = secure_filename(f.filename)
    file_path = os.path.join(app.config['UPLOAD_PATH'], file_name)
    f.save(file_path)
    print(f"{file_path} uploaded")

    _emit_progress(sid, {'percent': 5, 'message': 'File uploaded', 'status': 'loading'})

    # Step 2: Write file information in the database. Stays synchronous (fast)
    # so the response can carry the new `id_file` back to the client straight
    # away, instead of only learning it later through a progress event.

    project_name = request.values.get('project')
    acquisition_date = request.values.get('acquisition_date')
    depth = request.values.get('depth')
    lat = request.values.get('lat')
    long = request.values.get('long')

    try:
        acquisition_date_dt = datetime.strptime(acquisition_date, '%Y-%m-%dT%H:%M:%S')
    except (TypeError, ValueError):
        os.remove(file_path)
        return jsonify({
            'error': 'bad_request',
            'message': 'acquisition_date must be an ISO datetime (YYYY-MM-DDTHH:MM:SS).',
        }), 400

    try:
        s = sf.SoundFile(file_path)
    except Exception:
        os.remove(file_path)
        return jsonify({
            'error': 'bad_request',
            'message': 'Could not read the uploaded file as audio (not a valid .wav?).',
        }), 400

    fs = s.samplerate
    duration = s.frames / fs

    _emit_progress(sid, {'percent': 8, 'message': 'Writing file information ...', 'status': 'loading'})

    with _db_lock:
        Database.open_connexion()
        try:
            if not Database.get_projects(name=project_name):
                Database.add_project(project_name, depth, lat, long)
                print(f"Project {project_name} added to database")

            id_project = Database.get_projects(name=project_name)["id_project"]
            print(f"Project {project_name} have id {id_project}")

            Database.add_file(file_name, acquisition_date, duration, fs, app.config['UPLOAD_PATH'], id_project)

            id_file = Database.get_files(name=file_name)["id_file"]

            # Fetched once here (species rarely change) and handed to the
            # background job, so `pipeline()` doesn't need its own database
            # connection open for the whole inference run - see
            # `_run_analysis_job` / `compute_pipline.pipeline`.
            categories = Database.get_categories()
            if isinstance(categories, dict):
                categories = [categories]
            species_map = {c["english_name"]: c["id_species"] for c in categories}
        finally:
            Database.close_connexion()

    print(f"File {file_name} added to database with id {id_file}")

    _emit_progress(sid, {'percent': 10, 'message': 'File information written', 'status': 'loading'})

    # Step 3+4: run the detection pipeline and persist its results in the
    # background (Phase 5 of the redesign, docs/redesign/ROADMAP.md) - the
    # request returns immediately with a job id, further progress (one message
    # per analysis window) is reported over Socket.IO to `sid` only.

    job_id = uuid.uuid4().hex
    socketio.start_background_task(
        _run_analysis_job, job_id, sid, file_path, file_name, id_file,
        acquisition_date_dt, duration, fs, species_map,
    )

    return jsonify({'job_id': job_id, 'id_file': id_file, 'status': 'processing'}), 202


